import {readFile,writeFile} from 'node:fs/promises';
// Keep each key beside its distractors in a human-reviewable editorial source.
const root=new URL('../',import.meta.url);
const text=await readFile(new URL('content/cases.txt',root),'utf8');
const aliases={pengelolaan:'lingkungan','etika-kolaborasi':'etika'};
const counters={PCK:0,PU:0},caseCounters={PCK:0,PU:0},questions=[],puTopicIds={};
const rotate=(items,offset)=>items.slice(offset).concat(items.slice(0,offset));
const letters=['A','B','C','D'];
for(const block of text.trim().split(/^@/m).filter(Boolean)){
 const [header,narrative,...rows]=block.trim().split(/\r?\n/);
 const [section,rawTopic,caseTitle]=header.split('|');
 if(!['PU','PCK'].includes(section)||rows.length!==5)throw Error('Invalid case: '+header);
 const topic=aliases[rawTopic]||rawTopic;
 const caseId=section+'-CASE-'+String(++caseCounters[section]).padStart(2,'0');
 for(const row of rows){
  const [kind,prompt,...fields]=row.split('|');
  const n=++counters[section],id=(section==='PCK'?'INF':'PU')+'-'+String(n).padStart(3,'0');
  if(fields.length!==5)throw Error('Invalid options/reason: '+id);
  let options,answer,categories,type;
  if(kind==='S'||kind==='M'){
   const items=fields.slice(0,4).map((label,i)=>({label,right:kind==='S'?i===0:i<2}));
   const arranged=rotate(n%2?items:items.toReversed(),(n+Math.floor(n/4))%4);
   options=Object.fromEntries(arranged.map((item,i)=>[letters[i],item.label]));
   const keys=arranged.flatMap((item,i)=>item.right?[letters[i]]:[]);
   type=kind==='S'?'single_choice':'multiple_response';answer=kind==='S'?keys[0]:keys;
  }else if(kind==='C'){
   type='category_matrix';categories=['Benar','Salah'];
   if(!/^[01]{3}$/.test(fields[3]))throw Error('Invalid category key: '+id);
   const items=fields.slice(0,3).map((label,i)=>({label,right:fields[3][i]==='1'}));
   const arranged=rotate(n%2?items:items.toReversed(),n%3);
   options=arranged.map((item,i)=>({id:String(i),text:item.label}));
   answer=Object.fromEntries(arranged.map((item,i)=>[String(i),item.right?'Benar':'Salah']));
  }else throw Error('Unknown response type: '+kind);
  const codes=section==='PCK'?['P.1','P.6','PF.2']:topic==='etika'?['K.2','S.1']:topic==='refleksi'?['P.6','PF.5']:['P.2','P.6'];
  questions.push({id,section,topic:section==='PCK'?topic:undefined,puTopic:section==='PU'?topic:undefined,type,stem:narrative+'\n\n'+prompt,options,answer,...(categories?{categories}:{}),explanation:fields[4],competency_codes:codes,source_ids:section==='PCK'?['R03','R05','R08']:['R03','R08'],bank_revision:'2026.3-cases',case_id:caseId,case_title:caseTitle});
  if(section==='PU')(puTopicIds[topic]??=[]).push(id);
 }
}
if(counters.PCK!==100||counters.PU!==70)throw Error('Unexpected composition '+JSON.stringify(counters));
const output='// Generated by scripts/build-bank.mjs from original editorial cases.\n'+
 'export const casePuTopicIds = '+JSON.stringify(puTopicIds,null,2)+';\n'+
 'export const caseQuestions = '+JSON.stringify(questions,null,2)+';\n';
await writeFile(new URL('dist/case-bank.js',root),output);
console.log(JSON.stringify({questions:counters,cases:caseCounters,types:Object.fromEntries(['single_choice','multiple_response','category_matrix'].map(type=>[type,questions.filter(q=>q.type===type).length]))}));
